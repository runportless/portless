import { expect, test } from '@playwright/test'
import { applicationRequest, authenticate, controlAPI, environmentPath, readDownload } from './helpers'
import { readE2EState } from './state'

test.describe.configure({ mode: 'serial' })

test('creates, captures, exports, repeats, and deletes recordings', async ({ page }) => {
  await authenticate(page, environmentPath('recordings'))
  await page.getByLabel('NAME', { exact: true }).fill('ui-recording')
  await page.getByLabel('Recording traffic scope').selectOption('checkout:orders')
  await page.getByRole('button', { name: /START RECORDING/ }).click()

  const activeRecording = page.locator('.recording-active-control')
  await expect(activeRecording).toContainText('ui-recording')
  await expect(activeRecording).toContainText('checkout → orders')
  expect((await applicationRequest('/checkout?sku=coffee-mug&quantity=1')).status).toBe(200)
  await activeRecording.getByRole('button', { name: 'STOP RECORDING' }).click()

  const recordingRow = (name: string) => page.locator('.recording-history-table tbody tr').filter({
    has: page.getByRole('button', { name: `Recording actions for ${name}`, exact: true }),
  })
  const row = recordingRow('ui-recording')
  await expect(row).toContainText('checkout → orders')
  await expect(row.locator('td').nth(1)).toHaveText('1')
  await expect(page.locator('.recording-history-table .sortable-column-sort-control')).toHaveCount(0)

  await row.getByRole('button', { name: 'Recording actions for ui-recording', exact: true }).click()
  const recordingMenu = row.getByRole('menu', { name: 'ui-recording recording actions' })
  await expect(recordingMenu).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await recordingMenu.getByRole('menuitem', { name: 'Export ui-recording' }).click()
  const download = await downloadEvent
  const exported = JSON.parse(await readDownload(await download.path())) as { recording: string; exchanges: Array<{ source: string; target: string }> }
  expect(exported.recording).toBe('ui-recording')
  expect(exported.exchanges).toHaveLength(1)
  expect(exported.exchanges[0]).toMatchObject({ source: 'checkout', target: 'orders' })

  const repeatRecording = row.getByRole('button', { name: 'Repeat recording ui-recording' })
  await expect(repeatRecording).toContainText('REPEAT')
  await repeatRecording.click()
  await expect(activeRecording).toContainText('ui-recording-2')
  await expect(repeatRecording).toBeDisabled()
  await activeRecording.getByRole('button', { name: 'STOP RECORDING' }).click()
  const repeatedRow = recordingRow('ui-recording-2')
  await expect(repeatedRow).toContainText('checkout → orders')

  await row.getByRole('button', { name: 'Recording actions for ui-recording', exact: true }).click()
  await expect(recordingMenu).toBeVisible()
  await recordingMenu.getByRole('menuitem', { name: 'Delete ui-recording' }).click()
  await recordingMenu.getByRole('menuitem', { name: 'Confirm delete ui-recording' }).click()
  await expect(row).toHaveCount(0)

  await repeatedRow.getByRole('button', { name: 'Recording actions for ui-recording-2', exact: true }).click()
  const repeatedMenu = repeatedRow.getByRole('menu', { name: 'ui-recording-2 recording actions' })
  await repeatedMenu.getByRole('menuitem', { name: 'Delete ui-recording-2' }).click()
  await repeatedMenu.getByRole('menuitem', { name: 'Confirm delete ui-recording-2' }).click()
  await expect(repeatedRow).toHaveCount(0)
})

test('creates a multi-service scenario, edits routes, and restores providers without restarting peers', async ({ page }) => {
  const state = readE2EState()
  type Runtime = { name: string; pid?: number; generation: number; status: string }
  type Snapshot = { services: Runtime[]; bindings: Array<{ service: string; provider: string; mock?: { scenario: string } }> }
  const before = await controlAPI<Snapshot>(`/api/v1/environments/${state.project}/${state.environment}`)
  const beforeByName = new Map(before.services.map((service) => [service.name, service]))
  await authenticate(page, environmentPath('mocks'))

  const scenarioHeaders = page.locator('.mock-scenario-row--header > .sortable-grid-header')
  await expect(scenarioHeaders.locator(':scope > span:first-child')).toHaveText(['State', 'Scenario', 'Services', 'Routes', 'Modified'])
  await page.getByRole('button', { name: 'CREATE SCENARIO', exact: true }).click()
  const scenarioDialog = page.getByRole('dialog', { name: 'Create Mock Scenario' })
  await expect(scenarioDialog).toBeVisible()
  await expect(page).toHaveURL(/\?tab=mocks$/)
  await expect(scenarioDialog.getByLabel('NAME', { exact: true })).toBeFocused()
  await scenarioDialog.getByLabel('NAME', { exact: true }).fill('sold-out')
  await expect(scenarioDialog.getByLabel('SERVICE', { exact: true })).toHaveCount(0)
  await scenarioDialog.getByLabel('DESCRIPTION').fill('Inventory has no available stock')
  await expect(scenarioDialog.getByLabel('PATH', { exact: true })).toHaveCount(0)

  const scenarioRequest = page.waitForRequest((request) => request.method() === 'POST' && request.url().endsWith('/mocks'))
  await scenarioDialog.getByRole('button', { name: 'CREATE SCENARIO', exact: true }).click()
  expect((await scenarioRequest).postDataJSON()).toEqual({ name: 'sold-out', description: 'Inventory has no available stock' })

  const scenarioWorkspace = page.getByRole('region', { name: 'sold-out mock scenario' })
  await expect(scenarioWorkspace).toBeVisible()
  await expect(page).toHaveURL(/tab=mocks&scenario=sold-out$/)
  await expect(scenarioWorkspace.locator('.mock-scenario-service-eyebrow')).toHaveText('NO SERVICES YET')
  await expect(scenarioWorkspace.locator('.mock-workspace-service')).toHaveCount(0)
  await expect(scenarioWorkspace.locator('.mock-scenario-context')).toHaveCount(0)
  await expect(scenarioWorkspace.locator('.mock-scenario-summary')).toHaveCount(0)
  await expect(scenarioWorkspace.locator('.mock-workspace-title .mock-enabled-state')).toHaveCount(0)
  await expect(scenarioWorkspace).toContainText('NO ROUTES YET')
  await expect(scenarioWorkspace.getByRole('switch', { name: 'sold-out enabled' })).toBeDisabled()
  const emptyScenarios = await controlAPI<{ scenarios: Array<{ name: string; routes: unknown[]; activation: { state: string; targetServices: string[]; activeServices: string[] } }> }>(`/api/v1/environments/${state.project}/${state.environment}/mocks`)
  expect(emptyScenarios.scenarios.find((scenario) => scenario.name === 'sold-out')).toMatchObject({ routes: [], activation: { state: 'disabled', targetServices: [], activeServices: [] } })
  const afterScenarioCreation = await controlAPI<Snapshot>(`/api/v1/environments/${state.project}/${state.environment}`)
  expect(afterScenarioCreation.bindings.find((binding) => binding.service === 'inventory')?.provider).toBe('local')
  expect(afterScenarioCreation.services.find((service) => service.name === 'inventory')?.pid).toBe(beforeByName.get('inventory')?.pid)

  await scenarioWorkspace.getByRole('button', { name: 'ADD FIRST ROUTE', exact: true }).click()
  await expect(page).toHaveURL(/tab=mocks&scenario=sold-out&workspace=route$/)
  const routeEditor = page.getByRole('region', { name: 'Create Route' })
  await expect(routeEditor).toBeVisible()
  await expect(routeEditor.getByLabel('PATH', { exact: true })).toBeFocused()
  await expect(routeEditor.getByText('PREVIEW', { exact: true })).toHaveCount(0)
  await routeEditor.getByLabel('SERVICE', { exact: true }).selectOption('inventory')
  await routeEditor.getByLabel('PATH', { exact: true }).fill('/inventory/{sku}')
  await routeEditor.getByLabel('RESPONSE STATUS').selectOption('200')
  await routeEditor.getByLabel('RESPONSE BODY').fill('{"available":false,"reason":"mocked sold out"}')
  await routeEditor.getByText('ADVANCED OPTIONS').click()
  await routeEditor.getByLabel('ROUTE NAME').fill('lookup')
  await routeEditor.getByRole('button', { name: 'Maximize route editor' }).click()
  await expect(routeEditor).toHaveClass(/is-maximized/)
  await expect(routeEditor.getByRole('button', { name: 'Restore route editor' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(routeEditor).not.toHaveClass(/is-maximized/)
  const normalHeight = await routeEditor.evaluate((element) => element.getBoundingClientRect().height)
  await routeEditor.getByRole('heading', { name: 'Create Route', exact: true }).click()
  await page.keyboard.press('Control+Shift+F')
  await expect(page.locator('.shell')).toHaveClass(/shell--focus-mode/)
  await expect.poll(() => routeEditor.evaluate((element) => element.getBoundingClientRect().height)).toBeGreaterThan(normalHeight)
  expect(await routeEditor.evaluate((element) => element.getBoundingClientRect().bottom)).toBeLessThanOrEqual(page.viewportSize()!.height)
  await page.keyboard.press('Control+Shift+F')
  await expect(page.locator('.shell')).not.toHaveClass(/shell--focus-mode/)
  await routeEditor.getByRole('button', { name: 'SAVE ROUTE', exact: true }).click()

  await expect(scenarioWorkspace).toBeVisible()
  await expect(page).toHaveURL(/tab=mocks&scenario=sold-out$/)
  await scenarioWorkspace.getByRole('button', { name: 'ADD ROUTE', exact: true }).click()
  const secondRouteEditor = page.getByRole('region', { name: 'Create Route' })
  await secondRouteEditor.getByLabel('SERVICE', { exact: true }).selectOption('orders')
  await secondRouteEditor.getByLabel('PATH', { exact: true }).fill('/health')
  await secondRouteEditor.getByText('ADVANCED OPTIONS').click()
  await secondRouteEditor.getByLabel('ROUTE NAME').fill('health')
  await secondRouteEditor.getByRole('button', { name: 'SAVE ROUTE', exact: true }).click()

  await expect(scenarioWorkspace).toBeVisible()
  const routeHeaders = scenarioWorkspace.locator('.mock-route-row--header > .sortable-grid-header')
  await expect(routeHeaders.locator(':scope > span:first-child')).toHaveText(['Service', 'Route', 'Match', 'Response', 'Delay', 'State'])
  await expect(scenarioWorkspace.locator('.mock-scenario-service-eyebrow')).toHaveText('SERVICES / inventory · orders')
  const routeNames = scenarioWorkspace.locator('.mock-route-row--interactive > strong:nth-child(2)')
  await expect(routeNames).toHaveText(['lookup', 'health'])
  await scenarioWorkspace.getByRole('button', { name: 'Sort Route ascending' }).click()
  await expect(routeNames).toHaveText(['health', 'lookup'])
  await scenarioWorkspace.getByRole('button', { name: 'Sort Route descending' }).click()
  await expect(routeNames).toHaveText(['lookup', 'health'])

  const routeRow = scenarioWorkspace.locator('.mock-route-row').filter({ hasText: 'lookup' })
  await expect(routeRow).toContainText('GET /inventory/{sku}')
  await expect(routeRow).toContainText('200')
  const routeEnabled = routeRow.getByRole('switch', { name: 'lookup route enabled' })
  const routeToggle = routeRow.locator('.mock-route-toggle')
  await expect(routeEnabled).toBeChecked()
  const disableRouteRequest = page.waitForRequest((request) => request.method() === 'PUT' && request.url().endsWith('/mocks/sold-out/routes/lookup'))
  await routeToggle.click()
  expect((await disableRouteRequest).postDataJSON()).toMatchObject({ name: 'lookup', enabled: false })
  await expect(routeEnabled).not.toBeChecked()
  await expect(routeRow.getByText('DISABLED', { exact: true })).toBeVisible()
  const enableRouteRequest = page.waitForRequest((request) => request.method() === 'PUT' && request.url().endsWith('/mocks/sold-out/routes/lookup'))
  await routeToggle.click()
  expect((await enableRouteRequest).postDataJSON()).toMatchObject({ name: 'lookup', enabled: true })
  await expect(routeEnabled).toBeChecked()
  await expect(routeRow.getByText('ENABLED', { exact: true })).toBeVisible()
  const enableScenario = scenarioWorkspace.getByRole('switch', { name: 'sold-out enabled' })
  await expect(enableScenario).toBeEnabled()
  await scenarioWorkspace.locator('.mock-scenario-toggle').click()
  await expect(enableScenario).toBeChecked({ timeout: 30_000 })

  await routeRow.click()
  await expect(page).toHaveURL(/tab=mocks&scenario=sold-out&workspace=route&route=lookup$/)
  const editRouteEditor = page.getByRole('region', { name: 'Edit Route' })
  await expect(editRouteEditor.getByLabel('PATH', { exact: true })).toHaveValue('/inventory/{sku}')
  await expect(editRouteEditor.getByLabel('ROUTE NAME')).toBeDisabled()
  await editRouteEditor.getByRole('button', { name: 'BACK TO SCENARIO' }).click()
  await expect(scenarioWorkspace).toBeVisible()
  await routeRow.getByRole('button', { name: 'Route actions for lookup' }).click()
  const routeMenu = routeRow.getByRole('menu', { name: 'lookup route actions' })
  await expect(routeMenu.getByRole('menuitem', { name: 'EDIT', exact: true })).toBeVisible()
  await expect(routeMenu.getByRole('menuitem', { name: 'Delete lookup' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(routeMenu).toHaveCount(0)

  for (let index = 3; index <= 11; index++) {
    const name = `pagination-${String(index).padStart(2, '0')}`
    await controlAPI(`/api/v1/environments/${state.project}/${state.environment}/mocks/sold-out/routes/${name}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ name, service: 'inventory', method: 'GET', path: `/${name}`, status: 200, headers: { 'Content-Type': 'application/json' }, body: '', delayMs: 0, enabled: true }),
    })
  }
  await page.reload()
  await expect(scenarioWorkspace).toBeVisible()
  const routesPagination = scenarioWorkspace.getByLabel('routes pagination')
  await expect(scenarioWorkspace.locator('.mock-route-row--interactive')).toHaveCount(10)
  await expect(routesPagination).toContainText('1–10 of 11')
  await routesPagination.getByRole('button', { name: 'Next routes page' }).click()
  await expect(scenarioWorkspace.locator('.mock-route-row--interactive')).toHaveCount(1)
  await expect(routesPagination).toContainText('11–11 of 11')
  await scenarioWorkspace.getByRole('button', { name: 'Sort Route ascending' }).click()
  await expect(scenarioWorkspace.locator('.mock-route-row--interactive')).toHaveCount(10)
  await expect(routesPagination).toContainText('1–10 of 11')

  await scenarioWorkspace.getByRole('button', { name: 'Back to mock scenarios' }).click()
  await expect(page).toHaveURL(/\?tab=mocks$/)
  const scenarioRow = page.locator('.mock-scenario-row').filter({ hasText: 'sold-out' })
  await expect(scenarioRow.locator(':scope > *').nth(3)).toHaveText('11')
  const scenarioState = scenarioRow.locator('.mock-enabled-state')
  await expect(scenarioState.getByText('Enabled', { exact: true })).toBeVisible()
  await expect(scenarioRow.locator('.mock-scenario-services')).toHaveText('inventory, orders')
  await expect(scenarioRow.locator('time.mock-scenario-row__modified')).toBeVisible()

  const mocked = await controlAPI<Snapshot>(`/api/v1/environments/${state.project}/${state.environment}`)
  const mockedByName = new Map(mocked.services.map((service) => [service.name, service]))
  expect(mockedByName.get('checkout')?.pid).toBe(beforeByName.get('checkout')?.pid)
  expect(mockedByName.get('orders')).toMatchObject({ status: 'ready', generation: beforeByName.get('orders')?.generation })
  expect(mockedByName.get('orders')?.pid || 0).toBe(0)
  expect(mockedByName.get('inventory')).toMatchObject({ status: 'ready', generation: beforeByName.get('inventory')?.generation })
  expect(mockedByName.get('inventory')?.pid || 0).toBe(0)
  expect(mocked.bindings.find((binding) => binding.service === 'inventory')).toMatchObject({ provider: 'mock', mock: { scenario: 'sold-out' } })
  expect(mocked.bindings.find((binding) => binding.service === 'orders')).toMatchObject({ provider: 'mock', mock: { scenario: 'sold-out' } })

  const checkout = await applicationRequest('/checkout?sku=coffee-mug&quantity=1')
  expect(checkout.status).toBe(409)
  expect(checkout.body).toContain('mocked sold out')
  await expect.poll(async () => {
    const traffic = await controlAPI<{ exchanges: Array<{ target: string; targetProvider?: string; mockScenario?: string; mockRoute?: string }> }>(`/api/v1/environments/${state.project}/${state.environment}/traffic/exchanges?protocol=http&limit=100`)
    return traffic.exchanges.some((exchange) => exchange.target === 'inventory' && exchange.targetProvider === 'mock' && exchange.mockScenario === 'sold-out' && exchange.mockRoute === 'lookup')
  }).toBe(true)

  await scenarioRow.getByRole('button', { name: 'Disable sold-out' }).click()
  await expect(scenarioRow.getByRole('button', { name: 'Enable sold-out' })).toBeEnabled({ timeout: 30_000 })
  await expect(scenarioState.getByText('Disabled', { exact: true })).toBeVisible()
  const restored = await controlAPI<Snapshot>(`/api/v1/environments/${state.project}/${state.environment}`)
  const restoredByName = new Map(restored.services.map((service) => [service.name, service]))
  expect(restoredByName.get('checkout')?.pid).toBe(beforeByName.get('checkout')?.pid)
  expect(restoredByName.get('orders')?.pid).toBeGreaterThan(0)
  expect(restoredByName.get('orders')?.generation).toBe((beforeByName.get('orders')?.generation || 0) + 1)
  expect(restoredByName.get('inventory')?.pid).toBeGreaterThan(0)
  expect(restoredByName.get('inventory')?.generation).toBe((beforeByName.get('inventory')?.generation || 0) + 1)
  for (const name of ['inventory', 'orders']) {
    expect(restored.bindings.find((binding) => binding.service === name)).toMatchObject({ provider: 'local' })
  }
  expect((await applicationRequest('/checkout?sku=coffee-mug&quantity=1')).status).toBe(200)

  await scenarioRow.getByRole('button', { name: 'Mock scenario actions for sold-out' }).click()
  const scenarioMenu = scenarioRow.getByRole('menu', { name: 'sold-out mock scenario actions' })
  await scenarioMenu.getByRole('menuitem', { name: 'Delete sold-out' }).click()
  await scenarioMenu.getByRole('menuitem', { name: 'Confirm delete sold-out' }).click()
  await expect(scenarioRow).toHaveCount(0)
})

test('applies, disables, re-enables, and deletes a persistent fault', async ({ page }) => {
  await authenticate(page, environmentPath('faults'))
  await page.getByRole('button', { name: 'CREATE FAULT', exact: true }).click()
  const faultDialog = page.getByRole('dialog', { name: 'Create Fault' })
  await expect(faultDialog.getByLabel('NAME', { exact: true })).toBeFocused()
  await faultDialog.getByLabel('NAME', { exact: true }).fill('ui-orders-fault')
  await faultDialog.getByLabel('Fault connection').selectOption('checkout:orders')
  await faultDialog.getByRole('button', { name: 'HTTP status' }).click()
  await faultDialog.getByLabel('HTTP status').selectOption('503')
  await faultDialog.getByRole('button', { name: 'CREATE FAULT', exact: true }).click()
  await expect(faultDialog).toHaveCount(0)

  const row = page.locator('.fault-table tbody tr').filter({ hasText: 'ui-orders-fault' })
  await expect(row).toContainText('until disabled')
  const failed = await applicationRequest('/checkout?sku=coffee-mug&quantity=1')
  expect(failed.status).toBe(502)
  expect(failed.body).toContain('orders: returned 503 Service Unavailable')

  await row.getByRole('button', { name: 'DISABLE' }).click()
  await expect(row.locator('td').nth(4)).toHaveText('1')
  expect((await applicationRequest('/checkout?sku=coffee-mug&quantity=1')).status).toBe(200)

  await row.getByRole('button', { name: 'ENABLE' }).click()
  await expect(row.getByRole('button', { name: 'DISABLE' })).toBeEnabled()
  await row.getByRole('button', { name: 'Fault actions for ui-orders-fault' }).click()
  const faultMenu = row.getByRole('menu', { name: 'ui-orders-fault fault actions' })
  await faultMenu.getByRole('menuitem', { name: 'Delete ui-orders-fault' }).click()
  await faultMenu.getByRole('menuitem', { name: 'Confirm delete ui-orders-fault' }).click()
  await expect(row).toHaveCount(0)
})
